-- ── Portfolio NAV / TWR ───────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS portfolio_snapshots (
    account         TEXT    NOT NULL,
    date            DATE    NOT NULL,
    equity_gbp      DOUBLE PRECISION,
    cash_gbp        DOUBLE PRECISION,
    total_nav_gbp   DOUBLE PRECISION,
    twr_index       DOUBLE PRECISION,
    net_invested    DOUBLE PRECISION,
    daily_return    DOUBLE PRECISION,
    bench_nav       DOUBLE PRECISION,
    run_timestamp   TIMESTAMPTZ,
    PRIMARY KEY (account, date)
);

CREATE TABLE IF NOT EXISTS portfolio_ticker_daily (
    account         TEXT    NOT NULL,
    date            DATE    NOT NULL,
    ticker          TEXT    NOT NULL,
    shares          DOUBLE PRECISION,
    price_gbp       DOUBLE PRECISION,
    value_gbp       DOUBLE PRECISION,
    weight          DOUBLE PRECISION,
    run_timestamp   TIMESTAMPTZ,
    PRIMARY KEY (account, date, ticker)
);

CREATE TABLE IF NOT EXISTS benchmark_snapshots (
    account         TEXT    NOT NULL,
    benchmark_label TEXT    NOT NULL,
    date            DATE    NOT NULL,
    total_nav_gbp   DOUBLE PRECISION,
    twr_index       DOUBLE PRECISION,
    daily_return    DOUBLE PRECISION,
    run_timestamp   TIMESTAMPTZ,
    PRIMARY KEY (account, benchmark_label, date)
);

CREATE TABLE IF NOT EXISTS benchmark_ticker_daily (
    account         TEXT    NOT NULL,
    benchmark_label TEXT    NOT NULL,
    date            DATE    NOT NULL,
    ticker          TEXT    NOT NULL,
    target_weight   DOUBLE PRECISION,
    price_gbp       DOUBLE PRECISION,
    value_gbp       DOUBLE PRECISION,
    run_timestamp   TIMESTAMPTZ,
    PRIMARY KEY (account, benchmark_label, date, ticker)
);

CREATE TABLE IF NOT EXISTS saved_benchmarks (
    name            TEXT    PRIMARY KEY,
    constituents    JSONB   NOT NULL,
    rebalance_freq  TEXT    NOT NULL DEFAULT 'Q',
    created_at      TIMESTAMPTZ,
    updated_at      TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS last_prices (
    account         TEXT    NOT NULL,
    ticker          TEXT    NOT NULL,
    price_gbp       DOUBLE PRECISION,
    run_timestamp   TIMESTAMPTZ,
    PRIMARY KEY (account, ticker)
);

CREATE TABLE IF NOT EXISTS run_log (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account         TEXT,
    run_type        TEXT,
    run_timestamp   TIMESTAMPTZ,
    rows_written    INTEGER,
    notes           TEXT
);

CREATE TABLE IF NOT EXISTS engine_audit (
    account         TEXT    PRIMARY KEY,
    audit_json      JSONB   NOT NULL
);

-- ── Holdings / ETF Metadata ───────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS etf_holdings (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    etf_ticker      TEXT    NOT NULL,
    upload_date     DATE    NOT NULL,
    provider        TEXT    NOT NULL,
    isin            TEXT,
    constituent_ticker TEXT,
    name            TEXT    NOT NULL,
    weight_pct      DOUBLE PRECISION    NOT NULL,
    asset_class     TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_etf_holdings_etf  ON etf_holdings(etf_ticker);
CREATE INDEX IF NOT EXISTS idx_etf_holdings_isin ON etf_holdings(isin);

CREATE TABLE IF NOT EXISTS constituent_metadata (
    isin            TEXT    PRIMARY KEY,
    ticker          TEXT,
    name            TEXT,
    sector          TEXT,
    industry        TEXT,
    country         TEXT,
    market_cap      DOUBLE PRECISION,
    fetched_at      TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS ticker_isin_map (
    ticker          TEXT    PRIMARY KEY,
    isin            TEXT    NOT NULL,
    updated_at      TIMESTAMPTZ NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_ticker_isin_isin ON ticker_isin_map(isin);

CREATE TABLE IF NOT EXISTS lookahead_cache (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account              TEXT    NOT NULL DEFAULT 'Consolidated',
    computed_at          TIMESTAMPTZ NOT NULL,
    etf_ticker           TEXT    NOT NULL,
    constituent_isin     TEXT,
    constituent_ticker   TEXT,
    constituent_name     TEXT,
    sector               TEXT,
    country              TEXT,
    etf_weight_pct       DOUBLE PRECISION,
    portfolio_weight_pct DOUBLE PRECISION,
    effective_value_gbp  DOUBLE PRECISION,
    asset_class          TEXT,
    has_holdings         INTEGER DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_cache_computed ON lookahead_cache(computed_at);
CREATE INDEX IF NOT EXISTS idx_cache_etf      ON lookahead_cache(etf_ticker);

CREATE TABLE IF NOT EXISTS staleness_registry (
    etf_ticker           TEXT    PRIMARY KEY,
    last_upload          DATE    NOT NULL,
    upload_count         INTEGER NOT NULL DEFAULT 1,
    row_count            INTEGER NOT NULL DEFAULT 0,
    provider             TEXT,
    stale_days_threshold INTEGER NOT NULL DEFAULT 60,
    coverage_warning     TEXT,
    is_synthetic         INTEGER NOT NULL DEFAULT 0,
    index_proxy_note     TEXT,
    ignore_look_through  INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS etf_kiid (
    etf_ticker          TEXT    PRIMARY KEY,
    full_name           TEXT,
    index_tracked       TEXT,
    replication_method  TEXT,
    domicile            TEXT,
    ucits               INTEGER,
    accumulating        INTEGER,
    ter                 DOUBLE PRECISION,
    isin                TEXT,
    updated_at          TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS movers_price_cache (
    cache_date DATE NOT NULL,
    period     TEXT NOT NULL,
    ticker     TEXT NOT NULL,
    price_return DOUBLE PRECISION,
    fetched_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (cache_date, period, ticker)
);
